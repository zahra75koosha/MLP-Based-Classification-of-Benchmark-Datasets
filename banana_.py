data=pd.read_csv("banana.csv")
data

train,test = train_test_split(data,test_size=0.3)

train_data = train[['At1','At2']]
test_data = test[['At1','At2']]

train_label= train['Class']
test_label= test['Class']

t_1=pd.get_dummies(train_label)
train_labels = t_1[[-1,1]]
train_labels

t_2=pd.get_dummies(test_label)
test_labels = t_2[[-1,1]]
test_labels

train_data=np.array(train_data)
test_data=np.array(test_data)

train_labels=np.array(train_labels)
test_labels=np.array(test_labels)

Model=Sequential()
Model.add(layers.Dense(15, activation='relu', input_shape=(2,)))
Model.add(layers.Dense(12, activation='relu'))
Model.add(layers.Dense(2, activation='softmax'))

optimizer = tf.keras.optimizers.Adam(learning_rate=0.001)

Model.compile(loss='categorical_crossentropy', optimizer=optimizer, metrics=['accuracy'])

result=Model.fit(train_data,train_labels,epochs=30, batch_size=10)

r= Model.evaluate(test_data,test_labels)
print('final test set loss: (:4f)'. format(result))