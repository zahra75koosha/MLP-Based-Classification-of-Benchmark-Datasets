data=pd.read_excel("Spiral_3.xlsx")
data

train,test = train_test_split(data,test_size=0.3)

train_data = train[['A','B']]
test_data = test[['A','B']]

train_label= train['C']
test_label= test['C']

t_1=pd.get_dummies(train_label)
train_labels = t_1[[1,2,3]]
train_labels

t_2=pd.get_dummies(test_label)
test_labels = t_2[[1,2,3]]
test_labels

train_labels=np.array(train_labels)
test_labels=np.array(test_labels)

train_data=np.array(train_data)
test_data=np.array(test_data)

Model=Sequential()
Model.add(layers.Dense(21, activation='relu', input_shape=(2,)))
Model.add(layers.Dense(21, activation='relu'))
Model.add(layers.Dense(3, activation='softmax'))

optimizer = tf.keras.optimizers.Adam(learning_rate=0.005)

Model.compile(loss='categorical_crossentropy', optimizer=optimizer, metrics=['accuracy'])

result=Model.fit(train_data,train_labels,epochs=349, batch_size=10)

r= Model.evaluate(test_data,test_labels)
print('final test set loss: (:4f)'.format(result))